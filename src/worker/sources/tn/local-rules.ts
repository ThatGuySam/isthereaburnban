export const tnLocalCalendars = rules.map(({ id, fips, scope = "part", stack, sourceName, sourceUrl, officialUrl = sourceUrl, review, hour = 6, ...rule }) => {
  const counties = fips.map((code) => {
    const county = COUNTY_BY_FIPS.get(code);
    if (county?.state !== "TN") throw new Error(`Invalid Tennessee local burning rule FIPS: ${code}`);
    return county;
  });
  const zone = tennesseeZone(counties[0]);
  if (counties.some((county) => tennesseeZone(county) !== zone)) throw new Error(`Mixed time zones in Tennessee burning rule: ${id}`);
  return {
    id, kind: review.kind,
    ...reviewedLocalCalendar({
      publisher: { id: `tn-${id}-rule`, state: "TN", scope, stack, sourceName, sourceUrl, officialUrl },
      counties, rule, review, zone, hour, lastReviewed: "November 24, 2026",
    }),
  };
});
