export const miLocalRules = rules.map(({
  id, counties, stack, sourceName, sourceUrl, officialUrl, review, zone = US_ZONES.Eastern, ...rule
}, index) => {
  const areas = counties.map((name) => {
    const match = countyByName("MI", name);
    if (!match) throw new Error(`Unknown Michigan local-rule county: ${name}`);
    return match;
  });
  const { source, parse } = reviewedLocalCalendar({
    publisher: { id: `mi-${id}`, state: "MI", scope: "part", stack, sourceName, sourceUrl, officialUrl: officialUrl ?? sourceUrl },
    counties: areas,
    rule,
    review,
    zone,
    hour: 5 + index % 14,
  });
  return {
    source: { ...source, reportingFips: areas.map(({ fips }) => fips) },
    parse,
    fixture: `${id}.${review.kind === "pdf" ? "pdf" : "html"}`,
  };
});
