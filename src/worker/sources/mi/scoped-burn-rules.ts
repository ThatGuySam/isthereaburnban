export const miScopedBurnRules = rules.map(({
  id, counties, stack, sourceName, sourceUrl, officialUrl = sourceUrl, review, ...rule
}, index) => {
  const areas = counties.map((name) => {
    const county = countyByName("MI", name);
    if (!county) throw new Error(`Unknown Michigan burning rule county: ${name}`);
    return county;
  });
  const { source, parse } = reviewedLocalCalendar({
    publisher: { id: `mi-${id}`, state: "MI", scope: "part", stack, sourceName, sourceUrl, officialUrl },
    counties: areas, rule, review, zone: US_ZONES.Eastern, hour: 3 + index % 17,
  });
  return {
    source: { ...source, reportingFips: areas.map(({ fips }) => fips) },
    parse,
    fixture: `${id}.${review.kind === "pdf-etag" ? "headers.json" : review.kind}`,
  };
});
