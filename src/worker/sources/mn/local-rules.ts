export const mnLocalCalendars = rules.map(({ id, areas, scope, stack, sourceName, sourceUrl, officialUrl = sourceUrl, review, ...rule }, index) => {
  const counties = areas.map((area) => {
    const county = countyByName("MN", area);
    if (!county) throw new Error(`Unknown Minnesota county ${area}`);
    return county;
  });
  const publisher = { id: `mn-${id}-local-rule`, state: "MN", scope, stack, sourceName, sourceUrl, officialUrl };
  const { source, parse } = reviewedLocalCalendar({
    publisher, counties, rule, review, zone: US_ZONES.Central, hour: (index * 5) % 24,
  });
  return {
    id, kind: review.kind, parse,
    source: { ...source, reportingFips: counties.map(({ fips }) => fips) },
  };
});
