export const idCountyCalendars = rules.map(({
  id, counties, sourceName, sourceUrl, officialUrl = sourceUrl, stack, review, zone = "Mountain", ...rule
}) => {
  const state = "ID";
  const mapped = counties.map((name) => {
    const county = countyByName(state, name);
    if (!county) throw new Error(`${id}: unknown Idaho county ${name}`);
    return county;
  });
  const { source, parse } = reviewedLocalCalendar({
    publisher: { id, state, scope: "part", stack, sourceName, sourceUrl, officialUrl },
    counties: mapped, rule, review, zone: US_ZONES[zone], hour: 2,
  });
  return {
    source: { ...source, reportingFips: mapped.map(({ fips }) => fips) },
    parse,
    fixture: `${id}-2026-11-26.${review.kind === "pdf" ? "pdf" : "html.gz"}`,
  };
});
