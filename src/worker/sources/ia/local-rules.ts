export const iaLocalCalendars = rules.map(({ id, fips, sourceName, stack, sourceUrl, officialUrl, scope, review, countyLinks, ...rule }) => {
  const counties = fips.map((code) => {
    const county = COUNTY_BY_FIPS.get(code);
    if (!county || county.state !== "IA") throw new Error(`Unknown Iowa county ${code}`);
    return { ...county, ...countyLinks?.[code] };
  });
  const { source, parse } = reviewedLocalCalendar({
    publisher: { id: `ia-rule-${id}`, state: "IA", sourceName, stack, sourceUrl, officialUrl: officialUrl ?? sourceUrl, scope },
    counties, rule, review, zone: US_ZONES.Central, hour: 4,
  });
  return { id, kind: review.kind, fips, source, parse };
});
