export const waCountyRules = rules.map(({ id, areas, sourceUrl, sourceName, stack, label, note, seasons, review }, index) => {
  const group = index % 6;
  const counties = areas.map(([name, scopeNote]) => {
    const county = countyByName("WA", name);
    if (!county) throw new Error(`Washington local rule: unknown county ${name}`);
    return { ...county, scopeNote };
  });
  const calendar = reviewedLocalCalendar({
    publisher: {
      id: `wa-${id}`, state: "WA", scope: "part", stack, sourceName, sourceUrl, officialUrl: sourceUrl,
    },
    counties, rule: { label, note, seasons, scopeNote: areas[0][1] }, review,
    zone: US_ZONES.Pacific, hour: 4 + group, standing: true,
  });
  return {
    ...calendar, fixture: `${id}.${review.kind === "pdf" ? "pdf" : "html"}`,
    source: { ...calendar.source, pollGroup: `wa-standing-rules-${group + 1}`, reportingFips: counties.map(({ fips }) => fips) },
  };
});
