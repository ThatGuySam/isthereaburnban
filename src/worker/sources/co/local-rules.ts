export const coLocalBurningRules = rules.map(({ county, label, note, scopeNote, seasons, hours, review, compressedFixture,
  scope = "part", officialUrl, ...publisher }) => {
  const areas = (typeof county === "string" ? [county] : county).map((name) => {
    const area = countyByName("CO", name);
    if (!area) throw new Error(`Unknown Colorado county: ${name}`);
    return area;
  });
  const { source, parse } = reviewedLocalCalendar({
    publisher: { ...publisher, state: "CO", scope, officialUrl: officialUrl ?? publisher.sourceUrl },
    counties: areas,
    rule: { label, note, scopeNote, seasons, hours },
    review,
    zone: US_ZONES.Mountain,
    hour: 5,
    standing: true,
  });
  const extension = review.kind === "pdf" ? "pdf" : compressedFixture ? "html.gz" : "html";
  return { source: { ...source, reportingFips: areas.map(({ fips }) => fips) }, parse,
    fixture: `${publisher.id.slice(3)}.${extension}` };
});
