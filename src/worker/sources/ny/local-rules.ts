export const nyCountyCalendars = rules.map(({
  id, counties: names, scope = "part", stack, sourceName, sourceUrl, officialUrl = sourceUrl, review, ...rule
}, index) => {
  const state = "NY";
  const counties = names.map((name) => {
    const county = countyByName(state, name);
    if (!county) throw new Error(`${id}: unknown New York county ${name}`);
    return county;
  });
  const { source, parse } = reviewedLocalCalendar({
    publisher: { id: `ny-${id}`, state, scope, stack, sourceName, sourceUrl, officialUrl },
    counties, rule, review, zone: US_ZONES.Eastern, hour: (6 + index) % 24, standing: true,
  });
  const extension = review.kind === "pdf-etag" ? "headers.json" : review.kind === "pdf" ? "pdf" : "html";
  return { source: { ...source, reportingFips: counties.map(({ fips }) => fips) }, parse, fixture: `${id}.${extension}` };
});
